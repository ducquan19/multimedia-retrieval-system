"""Generate frontend/src/api/schema.gen.ts from the backend's OpenAPI schema.

The frontend's response types come from this file, so a field renamed or retyped in a
Pydantic model breaks the TypeScript build instead of the running UI. The app is built with a
dummy services factory: no model, index or data is loaded.

    python scripts/generate_api_types.py           # rewrite the file
    python scripts/generate_api_types.py --check   # exit 1 when it is out of date (CI)

Every component schema becomes an interface. Responses serialize every field (the API never
excludes unset or None fields), so all of them are required in ``Name``; schemas reachable from
a request body also get a ``NameInput`` variant where fields with a default are optional, as
the API accepts them omitted.
"""

import argparse
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend" / "src"))

OUTPUT = ROOT / "frontend" / "src" / "api" / "schema.gen.ts"
HEADER = (
    "// Generated by scripts/generate_api_types.py from the backend OpenAPI schema.\n"
    "// Do not edit: change the Pydantic models and run the script again."
)


def build_spec() -> dict[str, Any]:
    from core.config import Settings
    from factories.factory import create_app

    settings = Settings(_env_file=None, log_dir=None)
    return create_app(settings, services_factory=lambda *_: None).openapi()


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[1]


def request_schemas(spec: dict[str, Any]) -> set[str]:
    """Component schemas reachable from any request body."""
    schemas = spec["components"]["schemas"]
    found: set[str] = set()

    def walk(node: Any) -> None:
        if isinstance(node, dict):
            if "$ref" in node:
                name = ref_name(node["$ref"])
                if name not in found:
                    found.add(name)
                    walk(schemas[name])
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    for operations in spec["paths"].values():
        for operation in operations.values():
            walk(operation.get("requestBody", {}))
    return found


class Generator:
    def __init__(self, inputs: set[str]) -> None:
        self.inputs = inputs

    def type_of(self, schema: dict[str, Any], *, input_mode: bool) -> str:
        if "$ref" in schema:
            name = ref_name(schema["$ref"])
            return f"{name}Input" if input_mode and name in self.inputs else name
        if "const" in schema:
            return literal(schema["const"])
        if "enum" in schema:
            return " | ".join(literal(value) for value in schema["enum"])
        for key in ("anyOf", "oneOf"):
            if key in schema:
                members = [self.type_of(s, input_mode=input_mode) for s in schema[key]]
                return " | ".join(dict.fromkeys(members))
        kind = schema.get("type")
        if kind == "array":
            item = self.type_of(schema.get("items", {}), input_mode=input_mode)
            return f"({item})[]" if "|" in item else f"{item}[]"
        if kind == "object" or "properties" in schema or "additionalProperties" in schema:
            if "properties" in schema:
                return self.object_body(schema, input_mode=input_mode, indent="  ")
            extra = schema.get("additionalProperties")
            value = self.type_of(extra, input_mode=input_mode) if isinstance(extra, dict) else ""
            return f"Record<string, {value or 'unknown'}>"
        return {
            "string": "string",
            "integer": "number",
            "number": "number",
            "boolean": "boolean",
            "null": "null",
        }.get(kind, "unknown")

    def object_body(self, schema: dict[str, Any], *, input_mode: bool, indent: str = "") -> str:
        required = set(schema.get("required", ()))
        lines = ["{"]
        for name, prop in schema.get("properties", {}).items():
            # Responses serialize every field, defaulted ones too; requests may leave those out.
            optional = input_mode and name not in required
            key = name if name.isidentifier() else f'"{name}"'
            value = self.type_of(prop, input_mode=input_mode)
            lines.append(f"{indent}  {key}{'?' if optional else ''}: {value};")
        lines.append(f"{indent}}}")
        return "\n".join(lines)

    def interface(self, name: str, schema: dict[str, Any], *, input_mode: bool) -> str:
        doc = schema.get("description", "").strip().splitlines()
        comment = f"/** {doc[0]} */\n" if doc else ""
        type_name = f"{name}Input" if input_mode else name
        if "properties" not in schema:
            return (
                f"{comment}export type {type_name} = {self.type_of(schema, input_mode=input_mode)};"
            )
        body = self.object_body(schema, input_mode=input_mode)
        return f"{comment}export interface {type_name} {body}"


def literal(value: Any) -> str:
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def render(spec: dict[str, Any]) -> str:
    schemas = spec["components"]["schemas"]
    inputs = request_schemas(spec)
    generator = Generator(inputs)
    blocks = [HEADER]
    for name in sorted(schemas):
        blocks.append(generator.interface(name, schemas[name], input_mode=False))
        if name in inputs:
            blocks.append(generator.interface(name, schemas[name], input_mode=True))
    return "\n\n".join(blocks) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when the file is outdated")
    args = parser.parse_args()

    content = render(build_spec())
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if args.check:
        if current != content:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date: run scripts/generate_api_types.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
